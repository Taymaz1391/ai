def _slug(text: str, index: int) -> str:
    return f"fact-{index:04d}"


def rows() -> list[dict]:
    out: list[dict] = []
    for country, capital in CAPITALS.items():
        if not capital:
            continue
        if country in MULTI_CAPITAL:
            continue
        out.append({
            "q": f"پایتخت {country} کجاست؟",
            "keys": [f"پایتخت {country}", f"{country} پایتخت", f"مرکز {country}"],
            "a": f"پایتخت **{country}** **{capital}** است.",
        })
    for country, text in MULTI_CAPITAL.items():
        out.append({
            "q": f"پایتخت {country} کجاست؟",
            "keys": [f"پایتخت {country}", f"{country} پایتخت", country],
            "a": text,
        })
    for continent, (peak, height, note) in PEAKS.items():
        out.append({
            "q": f"بلندترین کوه {continent} کدام است؟",
            "keys": [f"بلندترین کوه {continent}", f"بلندترین قله {continent}",
                     f"بلندترین قلهٔ {continent}", peak],
            "a": f"بلندترین کوهِ **{continent}** **{peak}** است؛ ارتفاعش حدودِ {height} متر و در {note}.",
        })
    for group in (HEALTH, HISTORY, LITERATURE, SCIENCE, WORLD, MATH_FACTS):
        for question, keys, answer in group:
            out.append({"q": question, "keys": list(keys), "a": answer})
    for index, row in enumerate(out, start=1):
        row["id"] = _slug(row["q"], index)
        row["source"] = "structured-facts:v1"
    return out


def _existing_questions() -> set[str]:
    seen: set[str] = set()
    for path in PACKS:
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError:
            continue
        for line in lines:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except ValueError:
                continue
            q = (row.get("q") or "").strip()
            if q:
                seen.add(q)
    return seen


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="فقط بررسی؛ چیزی نمی‌نویسد")
    args = parser.parse_args()

    entries = rows()
    questions = [row["q"] for row in entries]
    if len(set(questions)) != len(questions):
        dupes = sorted({q for q in questions if questions.count(q) > 1})
        sys.exit(f"پرسشِ تکراری در جدول‌ها: {dupes}")
    ids = [row["id"] for row in entries]
    if len(set(ids)) != len(ids):
        sys.exit("شناسهٔ تکراری")

    existing = _existing_questions()
    fresh = [row for row in entries if row["q"] not in existing]
    skipped = len(entries) - len(fresh)

    if args.check:
        print(f"{len(entries)} ورودی؛ {skipped} تکراری؛ {len(fresh)} تازه")
        return

    OUT.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in fresh),
                   encoding="utf-8")
    print(f"نوشته شد: {OUT} — {len(fresh)} ورودی ({skipped} ورودیِ تکراری کنار گذاشته شد)")


if __name__ == "__main__":
    main()
