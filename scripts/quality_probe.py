# نشانه‌های پاسخِ ردشده (پیشنهاد به‌جای جواب)
EVASIVE = ("نمی‌دانم", "نمی دانم", "نمی‌توانم", "پیشنهاد می‌کنم", "دکمهٔ وب", "دکمه وب",
           "کلید «وب»", "اطلاع ندارم", "به‌روز نیستم", "به روز نیستم")


def ask(base: str, question: str, cookie: str = "", timeout: float = 40.0,
        retries: int = 3) -> dict:
    """پرسش از API؛ در صورت محدودیت نرخ یا سهمیه، با فاصله دوباره تلاش می‌شود."""
    body = json.dumps({"message": question}).encode("utf-8")
    req = urllib.request.Request(f"{base}/api/chat", data=body,
                                 headers={"content-type": "application/json",
                                          **({"cookie": cookie} if cookie else {})})
    started = time.time()
    try:
        with urllib.request.urlopen(req, timeout=timeout) as res:
            data = json.loads(res.read())
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", "replace")[:200]
        if exc.code in (429, 503) and retries > 0:
            time.sleep(2.0)
            return ask(base, question, cookie=cookie, timeout=timeout, retries=retries - 1)
        return {"error": exc.code, "detail": detail, "seconds": time.time() - started}
    except Exception as exc:  # noqa: BLE001 - خطای شبکه نباید سنجش را بشکند
        return {"error": type(exc).__name__, "detail": str(exc)[:200],
                "seconds": time.time() - started}
    data["seconds"] = time.time() - started
    return data


def judge(case: dict, answer: str) -> tuple[bool, list[str], list[str]]:
    """آیا پاسخ هر گروهِ واژه‌ها را دارد، و آیا از پاسخِ ردشده پرهیز کرده است؟"""
    text = (answer or "").replace("\u200c", " ").replace("\u200f", "")
    flat = re.sub(r"\s+", " ", text).lower()
    compact = flat.replace(" ", "")
    missing: list[str] = []
    for group in case["want"]:
        if not any(word.replace("\u200c", " ").lower() in flat
                   or word.replace("\u200c", " ").replace(" ", "").lower() in compact
                   for word in group):
            missing.append("/".join(group))
    evasive = [marker for marker in EVASIVE if marker in text][:2]
    short_ok = ("گفتگو", "ریاضی", "ترجمه")
    min_len = 4 if case["cat"] in short_ok else (10 if missing == [] else 60)
    long_enough = len(text) >= min_len
    return (not missing and not evasive and long_enough), missing, evasive


def run(base: str, cookie: str = "", delay: float = 0.0,
        cases: list[dict] | None = None) -> dict:
    cases = cases or CASES
    rows: list[dict] = []
    for case in cases:
        out = ask(base, case["q"], cookie=cookie)
        answer = out.get("answer") or ""
        ok, missing, evasive = judge(case, answer)
        if out.get("error"):
            ok, missing, evasive = False, missing, evasive
        rows.append({"q": case["q"], "cat": case["cat"], "ok": ok, "missing": missing,
                     "evasive": evasive, "answer": answer[:600],
                     "error": out.get("error"), "detail": out.get("detail"),
                     "seconds": round(out.get("seconds", 0.0), 3),
                     "engine": out.get("engine")})
        mark = "✓" if ok else "✗"
        print(f"  {mark} [{case['cat']}] {case['q'][:48]}", flush=True)
        if not ok:
            reason = f"نیامده: {missing}" if missing else ""
            if evasive:
                reason += f" پرهیز: {evasive}"
            print(f"      {reason or 'پاسخ کوتاه/خالی'} ← {answer[:90]!r}", flush=True)
        if delay:
            time.sleep(delay)
    passed = sum(1 for row in rows if row["ok"])
    times = [row["seconds"] for row in rows if row.get("seconds")]
    by_cat: dict[str, list[bool]] = {}
    for row in rows:
        by_cat.setdefault(row["cat"], []).append(row["ok"])
    return {
        "cases": len(rows),
        "passed": passed,
        "score": round(100 * passed / len(rows), 1) if rows else 0.0,
        "latency_p50_s": round(statistics.median(times), 3) if times else None,
        "by_category": {cat: round(100 * sum(vals) / len(vals), 1)
                        for cat, vals in by_cat.items()},
        "missed": [{"q": row["q"], "missing": row["missing"], "evasive": row["evasive"]}
                   for row in rows if not row["ok"]],
        "rows": rows,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="سنجش کیفیتِ پاسخ‌های رایان")
    parser.add_argument("--api", default=os.environ.get("RAYAN_API", "http://localhost:8000"))
    parser.add_argument("--cookie", default=os.environ.get("RAYAN_COOKIE", ""))
    parser.add_argument("--set", default="probe", choices=tuple(SETS))
    parser.add_argument("--delay", type=float, default=0.0)
    parser.add_argument("--json", action="store_true", help="خروجی ماشین‌خوان")
    parser.add_argument("--write", action="store_true", help="ذخیره در reports/quality.json")
    parser.add_argument("--out", default="")
    args = parser.parse_args()

    chosen = SETS[args.set]
    if not args.json:
        print(f"سنجش «{args.set}» روی {args.api} — {len(chosen)} پرسش", flush=True)
    result = run(args.api.rstrip("/"), cookie=args.cookie, delay=args.delay, cases=chosen)
    result["set"] = args.set
    result["api"] = args.api

    if args.json:
        print(json.dumps({k: v for k, v in result.items() if k != "rows"},
                         ensure_ascii=False, indent=2))
    else:
        print(f"\nامتیاز کیفیت: {result['score']}٪  ·  قبولی: {result['passed']}/{result['cases']}"
              f"  ·  میانهٔ تأخیر: {result['latency_p50_s']}s")
        for cat, score in result["by_category"].items():
            print(f"  {cat}: {score}٪")
        if result["missed"]:
            print("\nموارد ردشده:")
            for miss in result["missed"]:
                print(f"  • {miss['q'][:60]}  ←  نیامده: {miss['missing']}  "
                      f"پیشنهاد: {miss['evasive']}")
    if args.write or args.out:
        target = args.out or REPORT
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, "w", encoding="utf-8") as handle:
            json.dump(result, handle, ensure_ascii=False, indent=1)
        if not args.json:
            print(f"\nذخیره شد: {target}")
    return 0 if result["score"] >= 90 else 1


if __name__ == "__main__":
    sys.exit(main())
