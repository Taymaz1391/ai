_COMPILED = [(name, re.compile(pattern, re.I), answer) for name, pattern, answer in _RULES]


def match(message: str) -> dict | None:
    """اگر پیام با یکی از مهارت‌ها جور باشد، پاسخ آماده برمی‌گرداند."""
    text = (message or "").strip()
    if not text or len(text) > 120:
        return None
    for name, pattern, answer in _COMPILED:
        if pattern.search(text):
            return {"skill": name, "answer": answer}
    return None


def names() -> list[str]:
    return [name for name, _pattern, _answer in _RULES]
