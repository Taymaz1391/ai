def _has(text: str, *words: str) -> bool:
    """آیا واژه (به‌صورت مستقل) در متن آمده است؟ «پیشنهادی» نباید «نهاد» شمرده شود."""
    for word in words:
        if re.search(rf"(?<!\w){re.escape(word)}(?!\w)", text):
            return True
    return False


