# مرزِ واژه در فارسی، نه \b لاتین: نیم‌فاصله و حروفِ فارسی هر دو واژه‌اند.
_FA_CLASS = "[\u0600-\u06FF\u200c]"


def _word_replace(text: str, casual: str, formal: str) -> str:
    """جای‌گذاری فقط وقتی واژه کامل است، نه میانِ واژهٔ دیگر.

    باگِ واقعی: جای‌گذاریِ سادهٔ «تو» → «شما»، «نمی‌توانم» را «نمی‌شماانم» می‌کرد.
    """
    pattern = rf"(?<!{_FA_CLASS}){re.escape(casual)}(?!{_FA_CLASS})"
    return re.sub(pattern, formal, text)


def _formalize_sentence(sentence: str) -> str:
    """جملهٔ محاوره‌ای را به لحنِ اداری/مؤدبانه برگردان می‌کند."""
    text = sentence.strip().strip(".!؟?")
    if re.search(r"ببخشید|شرمنده", text) and re.search(r"دیر|تأخیر", text):
        return "از تأخیرِ پیش‌آمده پوزش می‌خواهم"
    for casual, formal in _FORMAL_REPLACE:
        text = _word_replace(text, casual, formal)
    return text.replace("  ", " ").strip()


def formalize(question: str) -> str | None:
    """«این جمله را رسمی‌تر کن: …» → نسخهٔ رسمیِ همان جمله، نه توصیه."""
    text = (question or "").strip()
    if not re.search(r"رسمی|مؤدبانه|مودبانه|اداری", text):
        return None
    payload = ""
    if ":" in text:
        payload = text.split(":", 1)[1]
    else:
        quoted = re.search(r"[«\"](.+?)[»\"]", text)
        if quoted:
            payload = quoted.group(1)
        else:
            payload = re.sub(r"^(?:لطفا|لطفاً)?\s*(?:این|آن)?\s*(?:جمله|متن|پیام)?\s*(?:را)?\s*"
                             r"(?:رسمی‌تر|مؤدبانه‌تر|مودبانه‌تر|اداری‌تر)\s*کن:?\s*", "", text)
    payload = (payload or "").strip().strip("«»\"'")
    if len(payload) < 3:
        return None
    pieces = [part for part in re.split(r"(?<=[.!؟])\s+", payload) if part.strip()]
    formal = " ".join(_formalize_sentence(part) + "." for part in pieces)
    formal = formal.replace("..", ".")
    # «سلام،» در نامهٔ رسمی تکرارِ «با سلام و احترام» است
    formal = re.sub(r"^\s*(?:سلام|درود|سلام علیکم)[،,]?\s*", "", formal).strip()
    formal = formal[:1].upper() + formal[1:] if formal else formal
    return ("**نسخهٔ رسمی**\n\n"
            f"با سلام و احترام،\n\n{formal}\n\n"
            "با سپاس" + "\n\n" +
            "اگر مخاطب خاصی دارد (مدیر، استاد، مشتری) بگو تا همان لحن را دقیق‌تر کنم.")


_SUMMARY_STOP = {"که", "را", "و", "در", "به", "از", "این", "آن", "با", "برای", "است",
                 "شد", "می", "هم", "بر", "تا", "یا", "اگر", "هر", "چه", "همه", "باید",
                 "شود", "کرد", "های", "ها", "یک", "دو", "سه", "نه", "اما", "نیز"}


def _key_terms(items: list[str], limit: int = 3) -> list[str]:
    """واژه‌های مشترک/پرتکرارِ نکته‌ها، بی‌آنکه ادعای تازه‌ای ساخته شود."""
    counts: dict[str, int] = {}
    for item in items:
        seen = set()
        for token in re.split(r"[\s،.,!؟?:؛]+", item):
            token = token.strip("«»\"'()")
            if len(token) < 3 or token in _SUMMARY_STOP or token in seen:
                continue
            seen.add(token)
            counts[token] = counts.get(token, 0) + 1
    ranked = sorted(counts.items(), key=lambda kv: (-kv[1], -len(kv[0])))
    return [word for word, n in ranked[:limit] if n >= 1]


def summarize(question: str) -> str | None:
    """«این سه نکته را خلاصه کن: …» → خلاصهٔ ساختاریافته از همان نکته‌ها."""
    text = (question or "").strip()
    if not _SUMMARY_ASK.search(text):
        return None
    payload = text.split(":", 1)[1] if ":" in text else ""
    if not payload:
        quoted = re.search(r"[«\"](.+?)[»\"]", text)
        payload = quoted.group(1) if quoted else text
    items = _split_items(payload)
    if len(items) < 2:
        return None
    bullets = "\n".join(f"• {item}" for item in items)
    count = "".join(_FA_DIGITS[int(d)] for d in str(len(items)))
    # «جمع‌بندی» فقط چیزی را می‌گوید که در متن بوده: شمارِ نکته‌ها و موضوعِ مشترک.
    key = _key_terms(items)
    line = f"جمع‌بندی: {count} نکتهٔ بالا خلاصهٔ متن است"
    if key:
        line += f"؛ موضوعِ مشترکِ آن‌ها «{'، '.join(key)}» است"
    return f"**خلاصهٔ {count} نکته**\n\n{bullets}\n\n**{line}.**"


def answer(question: str) -> dict | None:
    """نوشتن یا راهنمای کاربردی؛ اگر هیچ‌کدام نبود، None تا مسیر عادی ادامه یابد."""
    text = (question or "").strip()
    if not text:
        return None
    quoted = _QUOTE_OF.search(text)
    if quoted and re.search(_WRITE_VERBS, text):
        return {"answer": f"متنِ اصلیِ {quoted.group(1)} را در حافظهٔ بررسی‌شده ندارم و "
                          "چیزی را هم به نامِ او نقل نمی‌کنم (نقلِ نادرست بدتر از نگفتن است).\n\n"
                          f"اگر بخواهی، یک متنِ تازه دربارهٔ {quoted.group(1)} یا با حال‌وهوای "
                          "او می‌نویسم — با این توضیح که ساختهٔ من است، نه از او.",
                "source": "نقلِ قول", "engine": "write"}
    formal = formalize(text)
    if formal:
        return {"answer": formal, "source": "بازنویسی", "engine": "write"}
    summary = summarize(text)
    if summary:
        return {"answer": summary, "source": "خلاصه", "engine": "write"}
    kind = _kind(text)
    if kind:
        topic = topic_of(text)
        if not topic:
            return None
        facts = _facts_about(topic)
        if kind == "occasion":
            body, label = _occasion(text), "پیام"
        elif kind == "story":
            body, label = _story(topic, facts), "داستان"
        elif kind == "letter":
            body, label = _letter(topic), "نامه"
        elif kind == "sentence":
            body, label = _sentence(topic, facts), "جمله"
        elif kind == "essay":
            body, label = _essay(topic, facts), "متن"
        else:
            body, label = _note(topic, facts), "یادداشت"
        return {"answer": body, "source": label, "engine": "write"}
    guide = _guide(text)
    if guide:
        return {"answer": guide, "source": "راهنما", "engine": "guide"}
    return None
