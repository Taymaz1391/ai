def _guide(question: str) -> str | None:
    text = (question or "").strip()
    if not text:
        return None
    if not re.search(r"چطور|چگونه|چه کار|چی کار|راه|پیشنهاد|بگو|بده|برنامه", text):
        return None
    for pattern, answer in _GUIDES:
        if re.search(pattern, text):
            return answer
    return None


# ══════════════════════════════════════════════════════ ۵) نقطهٔ ورود

def answer(question: str) -> dict | None:
    """نوشتن یا راهنمای کاربردی؛ اگر هیچ‌کدام نبود، None تا مسیر عادی ادامه یابد."""
    text = (question or "").strip()
    if not text:
        return None
    kind = _kind(text)
    if kind:
        topic = topic_of(text)
        if not topic:
            return None
        facts = _facts_about(topic)
        if kind == "story":
            body, label = _story(topic, facts), "داستان"
        elif kind == "letter":
            body, label = _letter(topic), "نامه"
        elif kind == "essay":
            body, label = _essay(topic, facts), "متن"
        else:
            body, label = _note(topic, facts), "یادداشت"
        return {"answer": body, "source": label, "engine": "write"}
    guide = _guide(text)
    if guide:
        return {"answer": guide, "source": "راهنما", "engine": "guide"}
    return None
