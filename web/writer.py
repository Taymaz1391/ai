def _note(topic: str, facts: list[str]) -> str:
    if facts:
        body = " ".join(facts)
        return (f"{topic} یکی از موضوع‌هایی است که هم در زندگی روزمره دیده می‌شود و هم جای "
                f"اندیشیدن دارد. {body}\n\n"
                f"اگر بخواهم کوتاه بگویم: {topic} را نباید فقط از یک زاویه دید؛ هر بار که "
                f"به آن برمی‌گردیم، نکتهٔ تازه‌ای پیدا می‌شود. همین است که نوشتن درباره‌اش "
                f"ارزش دارد.")
    return (f"{topic} موضوعی است که می‌شود از چند زاویه به آن نگاه کرد. یک راه این است که "
            f"از تجربهٔ خودمان شروع کنیم: چه چیزی دربارهٔ {topic} دیده‌ایم و چه چیزی را "
            f"فقط شنیده‌ایم؟ راه دوم این است که پرسش را کوچک‌تر کنیم و ببینیم دقیقاً چه "
            f"می‌خواهیم بدانیم.\n\n"
            f"کوتاه اینکه {topic} با پرسیدن روشن می‌شود، نه با حدس‌زدن. اگر بخواهی، همین "
            f"یادداشت را با هم بلندتر می‌کنیم.")


def _sentence(topic: str, facts: list[str]) -> str:
    """سه جملهٔ کوتاهِ پیشنهادی دربارهٔ موضوع، تا کاربر یکی را بردارد."""
    seed = sum(ord(ch) for ch in topic) % 3
    options = (
        (f"{topic} از راه می‌رسد و بی‌آنکه اجازه بگیرد، حالِ آن روز را عوض می‌کند.",
         f"در {topic} چیزی هست که آدم را ناخواسته کمی آهسته‌تر می‌کند.",
         f"{topic} را باید دید؛ خواندنِ صدبارهٔ وصفش جای آن را نمی‌گیرد."),
        (f"{topic} همان چیزی است که تا نیاید، قدرش را نمی‌دانیم.",
         f"وقتی {topic} هست، حتی ساده‌ترین کارها هم مزهٔ دیگری دارند.",
         f"{topic} یادمان می‌اندازد که بعضی چیزها را نمی‌شود به تعویق انداخت."),
        (f"{topic} را می‌شود در یک کلمه گفت، ولی در یک جمله بهتر فهمیده می‌شود.",
         f"{topic} مثل پنجره‌ای است که از آن، روزِ معمولی بزرگ‌تر به نظر می‌رسد.",
         f"آدم‌ها {topic} را فراموش می‌کنند، ولی {topic} آدم‌ها را نه."),
    )[seed]
    lines = [f"**سه جملهٔ پیشنهادی دربارهٔ {topic}**\n"]
    lines += [f"{'۱۲۳'[i]}. {text}" for i, text in enumerate(options)]
    if facts:
        lines.append(f"\nیک نکتهٔ دقیق هم که می‌شود به متن اضافه کرد: {facts[0]}")
    lines.append("\nیکی را بردار، یا بگو کوتاه‌تر، شاعرانه‌تر یا رسمی‌ترش کنم.")
    return "\n".join(lines)


