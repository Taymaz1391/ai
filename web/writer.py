"""نویسندهٔ رایان — برای درخواست‌های نوشتاری و پرسش‌های کاربردی.

دو مسئله را حل می‌کند:

۱. **درخواست نوشتن** («یادداشتی دربارهٔ پاییز بنویس»، «داستان کوتاهی دربارهٔ باران
   بنویس»). پیش از این، این پرسش‌ها به دانشنامه می‌رفتند و به‌جای متن، تعریفِ
   واژه برمی‌گشت. اینجا متن ساخته می‌شود: برای یادداشت و مقاله، دو یا سه جمله از
   دانشِ موجود دربارهٔ موضوع گرفته و در قالبی نوشتاری بازچینی می‌شود؛ برای داستان،
   پیش‌نویسِ کوتاه با ساختِ روایی ساخته می‌شود.

۲. **پرسش‌های کاربردی** («چطور بهتر بخوابم؟»). پاسخ‌ها راهنمایی عمومی و شناخته‌شده‌اند،
   نه تشخیص و نه نسخه؛ همین هم در متن گفته می‌شود.

هیچ‌جا ادعا نمی‌شود این متن‌ها ساختهٔ مدل بزرگ‌اند؛ همه قطعی و قابل بازبینی‌اند.
"""
from __future__ import annotations

import re

# ══════════════════════════════════════════════════════ ۱) تشخیص خواسته

_WRITE_KINDS = (
    ("story", r"داستان|قصه|حکایت"),
    ("note", r"یادداشت|یاداشتی"),
    ("letter", r"نامه|پیام|ایمیل"),
    ("essay", r"مقاله|متن|توضیح|پاراگراف"),
)

_WRITE_VERBS = r"بنویس|بنویسید|بگو|بساز|تحریر|درست کن|تهیه کن"

_STOP_TOPIC = ("دربارهٔ", "درباره", "راجع به", "در مورد", "از", "برای")


def _kind(question: str) -> str | None:
    text = (question or "").strip()
    if not text or not re.search(_WRITE_VERBS, text):
        return None
    # شعر را دست نمی‌زنیم: از پیکره بیت واقعی می‌آید
    if re.search(r"شعر|بیت|غزل|رباعی", text):
        return None
    for name, pattern in _WRITE_KINDS:
        if re.search(pattern, text):
            return name
    return None


_KIND_STEMS = ("یادداشت", "داستان", "قصه", "نامه", "پیام", "ایمیل", "مقاله", "متن",
               "پاراگراف", "کوتاه", "یک", "یه", "خوب", "زیبا", "ساده")


def topic_of(question: str) -> str:
    """موضوع را از دلِ درخواست بیرون می‌کشد: «یادداشتی دربارهٔ پاییز بنویس» → «پاییز»."""
    text = (question or "").strip().rstrip(".!؟?")
    text = re.sub(_WRITE_VERBS, " ", text)
    kept: list[str] = []
    for token in re.split(r"\s+", text):
        word = token.strip(" ،؛:«»\"'")
        if not word or word in _STOP_TOPIC:
            continue
        if any(word.startswith(stem) for stem in _KIND_STEMS):
            continue
        kept.append(word)
    return " ".join(kept)[:60].strip()


# ══════════════════════════════════════════════════════ ۲) دانش پشتیبان

_JUNK_CUES = ("نگاره", "تصویر", "عکس", "پرونده", "جمعیت", "مساحت", "کد ISO",
              "پانویس", "منبع:", "رده:")


def _clean_sentence(part: str) -> str:
    part = re.sub(r"\([^)]{0,60}\)", "", part)
    part = re.sub(r"\s{2,}", " ", part).strip()
    return part


def _facts_about(topic: str) -> list[str]:
    """دو جملهٔ دانشیِ تمیز دربارهٔ موضوع؛ اگر نبود، فهرست خالی."""
    try:
        from web import retrieval
        entry = retrieval.wiki_lookup(topic)
    except Exception:  # noqa: BLE001 - نبودِ دانش نباید نوشتن را بشکند
        return []
    if not entry:
        return []
    title = (entry.get("title") or "").strip()
    phrase = (entry.get("phrase") or "").strip()
    lines = []
    for line in (entry.get("lead") or "").split("\n"):
        stripped = line.strip()
        if stripped and stripped in (title, phrase):
            continue                       # سرصفحهٔ تکراری مقاله
        lines.append(stripped)
    lead = re.sub(r"\s{2,}", " ", " ".join(lines)).strip()
    # سرصفحه‌های تکراری پیش از جملهٔ اصلی («بارش باران بارش باران باران (...)»)
    if phrase:
        cut = lead.rfind(phrase, 0, 90)
        if cut > 0:
            lead = lead[cut:].strip()
    out: list[str] = []
    for part in re.split(r"(?<=[.!؟])\s+", lead):
        sentence = _clean_sentence(part)
        if len(sentence) < 45 or len(sentence) > 260:
            continue
        if any(cue in sentence for cue in _JUNK_CUES):
            continue
        words_list = sentence.split()
        if len(words_list) < 6:
            continue
        if any(word in sentence for word in ("px", "http", "thumb", "اینجا")):
            continue
        # جملهٔ تکراری/بی‌معنا (کپشن تصویر) نباید به متن برود
        grams = [" ".join(words_list[i:i + 2]) for i in range(len(words_list) - 1)]
        if grams and len(set(grams)) / len(grams) < 0.75:
            continue
        if len(set(words_list)) / len(words_list) < 0.6:
            continue
        out.append(sentence)
        if len(out) == 2:
            break
    return out


# ══════════════════════════════════════════════════════ ۳) سازندهٔ متن

def _note(topic: str, facts: list[str]) -> str:
    if facts:
        body = " ".join(facts)
        return (f"{topic} یکی از موضوع‌هایی است که هم در زندگی روزمره دیده می‌شود و هم جای "
                f"اندیشیدن دارد. {body}\n\n"
                f"اگر بخواهم کوتاه بگویم: {topic} را نباید فقط از یک زاویه دید؛ هر بار که "
                f"به آن برمی‌گردیم، نکتهٔ تازه‌ای پیدا می‌شود. همین است که نوشتن درباره‌اش "
                f"ارزش دارد.")
    return (f"{topic} موضوعی است که می‌شود از چند زاویه به آن نگاه کرد. یک راه این است که "
            f"از تجربهٔ خودمان شروع کنیم: چه چیزی دربارهٔ {topic} دیده‌ایم و چه چیزی را "
            f"فقط شنیده‌ایم؟ راه دوم این است که پرسش را کوچک‌تر کنیم و ببینیم دقیقاً چه "
            f"می‌خواهیم بدانیم.\n\n"
            f"کوتاه اینکه {topic} با پرسیدن روشن می‌شود، نه با حدس‌زدن. اگر بخواهی، همین "
            f"یادداشت را با هم بلندتر می‌کنیم.")


def _story(topic: str, facts: list[str]) -> str:
    seed = sum(ord(ch) for ch in topic) % 3
    openings = (
        f"از همان صبح، {topic} همه‌جا بود؛ انگار شهر تصمیم گرفته بود امروز دربارهٔ آن حرف بزند.",
        f"باران که شروع شد، {topic} هم آمد؛ بی‌صدا، مثل کسی که سال‌ها منتظر مانده باشد.",
        f"هیچ‌کس نفهمید {topic} از کجا آمد؛ فقط همه حس کردند چیزی عوض شده است.",
    )
    middles = (
        "مردم اول توجه نکردند. بعد یکی ایستاد، بعد دو نفر، و بعد سکوت شد؛ "
        "سکوتی که در آن هر کس چیزی از خودش می‌شنید.",
        "کسی خواست توضیح بدهد و نتوانست. کسی خندید و بعد خنده‌اش گرفت؛ "
        "و همین کافی بود تا همه بفهمند ماجرا جدی‌تر از یک اتفاق ساده است.",
        "پیرمردی از کنار خیابان گفت که این را سال‌ها پیش هم دیده بود؛ "
        "اما هیچ‌کس دقیقاً یادش نمی‌آمد چه شده بود.",
    )
    endings = (
        "وقتی شب شد، {t} رفته بود، اما چیزی از خودش جا گذاشته بود که کسی نمی‌توانست "
        "نامش را ببرد — و همین کافی بود.",
        "صبح روز بعد همه سرِ کارشان رفتند و هیچ‌کس دربارهٔ {t} حرف نزد؛ "
        "انگار قرار بود فراموش شود، ولی فراموش نشد.",
        "داستان همین‌جا تمام می‌شود، ولی {t} تمام نشد؛ {t} ماند و منتظر ماند.",
    )
    parts = [openings[seed], middles[seed]]
    if facts:
        parts.append("در آن میان، کسی دفتری باز کرد و نوشت: " + facts[0])
    parts.append(endings[seed].replace("{t}", topic))
    return "\n\n".join(parts)


def _letter(topic: str) -> str:
    return ("سلام،\n\n"
            f"می‌خواستم چند خطی دربارهٔ {topic} بنویسم. مدتی است به آن فکر می‌کنم و هر بار "
            f"به این نتیجه می‌رسم که بهتر است درباره‌اش حرف بزنیم، نه اینکه هر کدام "
            f"در ذهن خودمان آن را بزرگ کنیم.\n\n"
            f"اگر وقت داشتی، بنویس تو دربارهٔ {topic} چه فکر می‌کنی. همین چند خط را "
            f"کافی نمی‌دانم، ولی برای شروع خوب است.\n\n"
            "با احترام")


def _essay(topic: str, facts: list[str]) -> str:
    body = " ".join(facts) if facts else ""
    first = (f"{topic} از موضوع‌هایی است که اگر دقیق نگاه کنیم، ساده نیست. "
             f"بیشتر ما اول یک تصویر کلی از آن داریم و بعد، وقتی وارد جزئیات می‌شویم، "
             f"می‌فهمیم چیزهایی هست که نمی‌دانستیم.")
    second = body or (f"برای شناختن {topic} باید پرسش را روشن کرد: دقیقاً دنبال چه هستیم؟ "
                      f"پاسخِ کلی به کار تصمیم‌گیری نمی‌آید.")
    third = (f"نتیجه اینکه {topic} را باید مرحله‌به‌مرحله شناخت. هر جمله‌ای که در این "
             f"باره می‌خوانیم یا می‌شنویم، یک تکه از تصویر است؛ تصویر کامل وقتی ساخته "
             f"می‌شود که خودمان هم چیزی به آن اضافه کنیم.")
    return f"{first}\n\n{second}\n\n{third}"


