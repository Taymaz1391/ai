from __future__ import annotations

import re

# ══════════════════════════════════════════════════════ ۱) تشخیص خواسته

_WRITE_KINDS = (
    ("occasion", r"تبریک|تسلیت|خسته نباشی|روزت مبارک|تولد|سالگرد"),
    ("story", r"داستان|قصه|حکایت"),
    ("note", r"یادداشت|یاداشتی"),
    ("letter", r"نامه|پیام|ایمیل"),
    ("sentence", r"جمله|سطر|یک خط|دوجمله"),
    ("essay", r"مقاله|متن|توضیح|پاراگراف"),
)

_WRITE_VERBS = r"بنویس|بنویسید|بگو|بساز|تحریر|درست کن|تهیه کن"
_FA_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")

_STOP_TOPIC = ("دربارهٔ", "درباره", "راجع به", "در مورد", "از", "برای")

# «یک جمله از حافظ بنویس» نقلِ قول می‌خواهد، نه متنِ ساختگیِ ما.
_QUOTE_OF = re.compile(r"(?:از|منسوب به)\s+(حافظ|سعدی|مولانا|مولوی|فردوسی|خیام|نظامی|"
                       r"نیما|شاملو|پروین|رهی معیری|قیصر)")


def _kind(question: str) -> str | None:
    text = (question or "").strip()
    if not text or not re.search(_WRITE_VERBS, text):
        return None
    # شعر را دست نمی‌زنیم: از پیکره بیت واقعی می‌آید
    if re.search(r"شعر|بیت|غزل|رباعی", text):
        return None
    for name, pattern in _WRITE_KINDS:
        if re.search(pattern, text):
            return name
    return None


_KIND_STEMS = ("یادداشت", "داستان", "قصه", "نامه", "پیام", "ایمیل", "مقاله", "متن",
               "پاراگراف", "جمله", "سطر", "کوتاه", "یک", "یه", "خوب", "زیبا", "ساده")


def topic_of(question: str) -> str:
    """موضوع را از دلِ درخواست بیرون می‌کشد: «یادداشتی دربارهٔ پاییز بنویس» → «پاییز»."""
    text = (question or "").strip().rstrip(".!؟?")
    text = re.sub(_WRITE_VERBS, " ", text)
    kept: list[str] = []
    for token in re.split(r"\s+", text):
        word = token.strip(" ،؛:«»\"'")
        if not word or word in _STOP_TOPIC:
            continue
        if any(word.startswith(stem) for stem in _KIND_STEMS):
            continue
        kept.append(word)
    return " ".join(kept)[:60].strip()


# ══════════════════════════════════════════════════════ ۲) دانش پشتیبان

_JUNK_CUES = ("نگاره", "تصویر", "عکس", "پرونده", "جمعیت", "مساحت", "کد ISO",
              "پانویس", "منبع:", "رده:")


def _clean_sentence(part: str) -> str:
    part = re.sub(r"\([^)]{0,60}\)", "", part)
    part = re.sub(r"\s{2,}", " ", part).strip()
    return part


def _facts_about(topic: str) -> list[str]:
    """دو جملهٔ دانشیِ تمیز دربارهٔ موضوع؛ اگر نبود، فهرست خالی."""
    try:
        from web import retrieval
        entry = retrieval.wiki_lookup(topic)
    except Exception:  # noqa: BLE001 - نبودِ دانش نباید نوشتن را بشکند
        return []
    if not entry:
        return []
    title = (entry.get("title") or "").strip()
    phrase = (entry.get("phrase") or "").strip()
    lines = []
    for line in (entry.get("lead") or "").split("\n"):
        stripped = line.strip()
        if stripped and stripped in (title, phrase):
            continue                       # سرصفحهٔ تکراری مقاله
        lines.append(stripped)
    lead = re.sub(r"\s{2,}", " ", " ".join(lines)).strip()
    # سرصفحه‌های تکراری پیش از جملهٔ اصلی («بارش باران بارش باران باران (...)»)
    if phrase:
        cut = lead.rfind(phrase, 0, 90)
        if cut > 0:
            lead = lead[cut:].strip()
    out: list[str] = []
    for part in re.split(r"(?<=[.!؟])\s+", lead):
        sentence = _clean_sentence(part)
        if len(sentence) < 45 or len(sentence) > 260:
            continue
        if any(cue in sentence for cue in _JUNK_CUES):
            continue
        words_list = sentence.split()
        if len(words_list) < 6:
            continue
        if any(word in sentence for word in ("px", "http", "thumb", "اینجا")):
            continue
        # جملهٔ تکراری/بی‌معنا (کپشن تصویر) نباید به متن برود
        grams = [" ".join(words_list[i:i + 2]) for i in range(len(words_list) - 1)]
        if grams and len(set(grams)) / len(grams) < 0.75:
            continue
        if len(set(words_list)) / len(words_list) < 0.6:
            continue
        out.append(sentence)
        if len(out) == 2:
            break
    return out


