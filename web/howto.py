def _subject_of(text: str) -> str:
    """موضوعِ خامِ پرسش، برای ساختنِ چارچوبِ عمومی."""
    cleaned = re.sub(r"(لطفا|لطفاً)\s*", "", text)
    cleaned = re.sub(r"(چطور|چگونه|چه\s*کنم|چه\s*کار\s*کنم|چی\s*کار\s*کنم|راهکار|چجوری|"
                     r"چه\s*باید\s*بکنم|می\s*شود|می\s*توانم|بکنم|کنم)\s*", "", cleaned)
    cleaned = re.sub(r"[؟?!.،؛]+", " ", cleaned)
    cleaned = re.sub(r"^(?:برای|در|از|با|به|دربارهٔ|درباره|روی)\s+", "", cleaned)
    return re.sub(r"\s+", " ", cleaned).strip(" ،")


