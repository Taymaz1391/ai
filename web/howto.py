    if _TECH.search(raw) or _SOCIAL.match(text) or len(text) < 10:
        return None

    asks = bool(_ASK.search(text))
    writing_task = bool(_WRITE_TASK.search(text))
    ranked = sorted(((_score(text, topic), topic) for topic in _TOPICS),
                    key=lambda item: item[0], reverse=True)
    best_score, best = ranked[0]

    # موضوعِ روشن، ولی فقط وقتی پرسش واقعاً راهنمایی می‌خواهد؛
    # «چه کسی لامپ را اختراع کرد؟» دانش است، نه راهنما.
    if best_score >= (2.0 if writing_task else 1.2) and asks:
        return {"answer": _compose(best), "engine": "guide", "guide": best["id"],
                "score": round(best_score, 2)}

    # چارچوبِ عمومی فقط برای پرسشِ واقعیِ «چطور…» با موضوعِ مشخص
    if not asks or writing_task:
        return None
    subject = _subject_of(raw)
    core = re.sub(r"^(?:انجام|کار|کارش|همین|این|آن)\s*", "", subject)
    core = re.sub(r"\s*(?:بدهم|بدهم|کنم|بکنم|کنیم|بشوم|بشویم|بدارم|شود|بشود)$", "", core).strip()
    if len(subject) < 6 or len(subject.split()) < 2 or len(core) < 4:
        return None                 # «چطور انجامش بدهم» موضوعِ مشخصی ندارد
    generic = _generic(subject)
    if generic:
        return {"answer": generic, "engine": "guide", "guide": "generic", "score": 0.0}
    return None
