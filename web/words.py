# ریخت‌های رایجِ پرسشی که پیش از واژه می‌آیند
_PREFIX = re.compile(r"^(?:معنی|معنای|تعریفِ?|مفهومِ?|ترجمهٔ|برابرِ)?\s*"
                     r"(?:واژهٔ?|واژه|کلمهٔ?|کلمه|لغتِ?|اصطلاحِ?)?\s*[«\"']?")
_SUFFIX = re.compile(r"[»\"']?\s*(?:است|هست)?\s*(?:چیست|چیه|چه\s*است|"
                     r"چه\s*معنایی\s*دارد|یعنی\s*(?:چه|چی)|به\s*چه\s*معناست)?\s*[؟?]?$")
_TAIL = re.compile(r"\s+(?:یعنی|به\s*معنی|به\s*معنای|چیست|چیه)\s*.*$")
_ZWNJ = "\u200c"


def _norm(word: str) -> str:
    text = (word or "").strip().strip("«»\"'،,.!؟?")
    text = text.replace(_ZWNJ, " ").replace("ي", "ی").replace("ك", "ک")
    return re.sub(r"\s+", " ", text).strip()


def _variants(key: str) -> list[str]:
    """ریخت‌های ساده‌شده: حذفِ «را»، «ها»، «ی» و نیم‌فاصله."""
    out = [key]
    for suffix in (" را", "ها", "های", "هایی", "ی", "ا"):
        if key.endswith(suffix) and len(key) - len(suffix) >= 2:
            out.append(key[: -len(suffix)].strip())
    return out


def meaning(word: str) -> dict | None:
    """تعریفِ فارسیِ واژه، اگر در واژه‌نامه باشد."""
    key = _norm(word)
    key = _PREFIX.sub("", key)
    key = _SUFFIX.sub("", key).strip()
    key = _TAIL.sub("", key).strip()
    key = re.sub(r"\s+(?:را|را)\s*$", "", key).strip()
    if not key or len(key) > 40:
        return None
    for candidate in _variants(key):
        hit = _DEFS.get(candidate)
        if hit:
            definition, kind, synonyms = hit
            return {"word": candidate, "definition": definition, "kind": kind,
                    "synonyms": list(synonyms)}
    return None


def exists(word: str) -> bool:
    return meaning(word) is not None


def count() -> int:
    return len(_DEFS)


def all_words() -> list[str]:
    return sorted(_DEFS)
