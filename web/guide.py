def _generic(subject: str, question: str) -> str:
    """وقتی موضوعِ مشخصی در فهرست نیست: روشِ اجراییِ متناسب با خودِ پرسش."""
    plain = subject or "این کار"
    wants_how = _has(question, "چطور", "چگونه", "چی کار", "چه کار", "راه")
    lead = (f"برای «{plain}» یک مسیرِ عملی هست که بدونِ آزمون‌وخطای طولانی جواب می‌دهد:"
            if wants_how else f"دربارهٔ «{plain}»، این چهار قدم تصمیم را روشن می‌کند:")
    steps = [
        f"نتیجهٔ دلخواه را در یک جمله بنویس: بعد از انجامِ «{plain}» چه چیزی باید عوض شده باشد؟",
        "وضعیتِ فعلی را اندازه بگیر — عدد، زمان یا یک نمونهٔ واقعی. بدونِ اندازه، پیشرفت دیده نمی‌شود.",
        "کوچک‌ترین قدمِ ممکن را همین امروز بردار؛ کاری که کمتر از ۳۰ دقیقه وقت بگیرد.",
        "بعد از یک هفته، همان اندازه‌گیری را تکرار کن و فقط یک چیز را عوض کن.",
    ]
    tail = "اگر جزئیاتِ بیشتری بدهی — شرایط، محدودیت‌ها یا هدفِ دقیق — همین مسیر را برای وضعیتِ خودت می‌چینم."
    return _compose("مسیرِ عملی", lead, steps, tail)


def topic_of(question: str) -> str | None:
    text = _normalize(question or "")
    topic = _topic_match(text)
    return topic["id"] if topic else None


def topics() -> list[str]:
    return [t["id"] for t in _TOPICS]


def answer(question: str) -> dict | None:
    """پاسخِ راهنمایی برای پرسش؛ اگر موضوعی نبود ``None``."""
    raw = (question or "").strip()
    if not raw or len(raw) > 400:
        return None
    # درخواستِ کدِ مشخص، راهنمای زندگی نیست؛ «یادگیریِ برنامه‌نویسی» هست
    if re.search(r"پایتون|python|(?<![\w\u200c])کد(?![\w\u200c])|جاوااسکریپت|تابع|فایل",
                 raw, re.I) and re.search(r"بنویس|بنویسم|بده|بخوانم|خطا|اجرا|دیباگ|تعریف|"
                                          r"چطور یک|چگونه یک", raw):
        return None
    text = _normalize(raw)
    topic = _topic_match(text)
    if topic:
        return {"answer": topic["build"](), "engine": "guide", "source": f"guide:{topic['id']}"}
    # پرسش‌های روش‌محورِ بی‌موضوع: «چطور X را انجام بدهم؟»
    if _has(text, "چطور", "چگونه") and len(re.findall(r"\w+", text)) >= 4:
        from web.retrieval import subject_phrase
        subject = " ".join(subject_phrase(raw)).strip()
        if subject and len(subject) >= 3:
            return {"answer": _generic(subject, text), "engine": "guide", "source": "guide:method"}
    return None
