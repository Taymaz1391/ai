_MARKS = re.compile("[\u064b-\u065f\u0670\u06d6-\u06ed]")


def _hit_kind(text: str, key: str) -> int:
    """۰ = نیست، ۱ = داخلِ واژهٔ دیگر، ۲ = واژهٔ کامل (مرزِ واژه)."""
    key = _normalize(key).lower()
    if not key:
        return 0
    if len(key) < 3:                     # کلیدِ کوتاه فقط با مرزِ کامل پذیرفته است
        pattern = rf"(?<![\w\u200c]){re.escape(key)}(?![\w\u200c])"
        return 2 if re.search(pattern, text) else 0
    if len(key) >= 3:
        pattern = rf"(?<![\w\u200c]){re.escape(key)}(?![\w\u200c])"
        if re.search(pattern, text):
            return 2
    if key in text:
        return 2 if len(key) < 3 else 1
    return 0


_CODEISH = re.compile(r"پایتون|python|جاوااسکریپت|(?<![\w\u200c])کد(?![\w\u200c])|"
                      r"فایل|تابع|اسکریپت|دیباگ|خطا")


def _topic_match(text: str):
    """موضوعی که بهترین امتیاز را دارد؛ واژهٔ داخلِ واژهٔ دیگر امتیازِ کمتری دارد."""
    text = _MARKS.sub("", _normalize(text)).lower()
    codeish = bool(_CODEISH.search(text))
    best, best_score = None, 0.0
    for order, topic in enumerate(_TOPICS):
        if codeish and topic["id"] not in ("programming", "git"):
            continue
        ambiguous = set(topic.get("ambiguous") or ())
        key_score = 0.0
        for key in topic["keys"]:
            kind = _hit_kind(text, key)
            if not kind:
                continue
            weight = 1.5 if key in ambiguous else 3.0
            key_score = max(key_score, weight if kind == 2 else 1.0)
        if key_score < 1.0:
            continue
        need_hits = sum(1 for word in topic["needs"] if _hit_kind(text, word))
        need_score = 2.0 if need_hits >= 2 else (0.6 if need_hits == 1 else 0.0)
        score = key_score + need_score - order * 0.001
        if score > best_score:
            best, best_score = topic, score
    return best


