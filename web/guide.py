import re

def _normalize(text: str) -> str:
    """یکسان‌سازیِ ساده: ی/ک عربی، نیم‌فاصله و فاصله‌های اضافی."""
    text = (text or "").replace("ي", "ی").replace("ك", "ک").replace("\u200c", " ")
    text = text.replace("\u200f", "").replace("\u200e", "")
    return " ".join(text.split())

