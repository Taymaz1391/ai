_FA_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def _steps(*items: str) -> str:
    return "\n".join(f"{str(i).translate(_FA_DIGITS)}. {item}" for i, item in enumerate(items, 1))


def _compose(title: str, lead: str, steps: list[str], tail: str = "") -> str:
    body = f"{title}\n{lead}\n\n{_steps(*steps)}"
    return body + (f"\n\n{tail}" if tail else "")


